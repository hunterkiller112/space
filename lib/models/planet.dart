class Planet {
  String name;
  String imagePath;
  String title;
  String about;
  String distanceFromSun;
  String dayLength;
  String orbitalPeriod;
  String radius;
  String mass;
  String gravity;
  String surfaceArea;

  Planet({
    required this.name,
    required this.imagePath,
    required this.title,
    required this.about,
    required this.distanceFromSun,
    required this.dayLength,
    required this.orbitalPeriod,
    required this.radius,
    required this.mass,
    required this.gravity,
    required this.surfaceArea,
  });
}
